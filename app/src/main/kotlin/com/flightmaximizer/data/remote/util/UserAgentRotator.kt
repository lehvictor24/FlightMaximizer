        "Mozilla/5.0 (X11; Ubuntu; Linux x86_64; rv:125.0) Gecko/20100101 Firefox/125.0",
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36 OPR/110.0.0.0"
    )

    private val acceptLanguages = listOf("en-US,en;q=0.9", "en-GB,en;q=0.9", "en-CA,en;q=0.9")

    fun next(): String = agents[random.nextInt(agents.size)]

    fun nextUserAgent(): String = next()

    fun nextAcceptLanguage(): String = acceptLanguages[random.nextInt(acceptLanguages.size)]
}
